"""
Unit and integration tests for Latency Masking (Acoustic Pre-roll).
Validates:
- Actions dynamically inject 'user_message' into OpenAI function parameter schema.
- ResilientChatGPTAgent call_function fallback guard injects persona-specific fillers
  when the LLM omits user_message.
- Preserves LLM-generated custom user_message when present.
"""
import json
import pytest
from unittest.mock import AsyncMock, patch, MagicMock

from vocode.streaming.models.actions import FunctionCall
from vocode.streaming.models.agent import ChatGPTAgentConfig
from vocode.streaming.models.message import BaseMessage
from backend.agent_factory import ResilientChatGPTAgent, SmartFallbackAgent
from backend.actions.appointment_actions import (
    CheckAvailabilityAction,
    CheckAvailabilityActionConfig,
    BookAppointmentAction,
    BookAppointmentActionConfig,
    CancelAppointmentAction,
    CancelAppointmentActionConfig,
)


def test_action_schemas_require_user_message():
    """Verify actions with should_respond='always' expose 'user_message' in their schema."""
    check_act = CheckAvailabilityAction(CheckAvailabilityActionConfig())
    schema_check = check_act.get_openai_function()["parameters"]
    assert "user_message" in schema_check["properties"]
    assert "user_message" in schema_check["required"]

    book_act = BookAppointmentAction(BookAppointmentActionConfig())
    schema_book = book_act.get_openai_function()["parameters"]
    assert "user_message" in schema_book["properties"]
    assert "user_message" in schema_book["required"]

    cancel_act = CancelAppointmentAction(CancelAppointmentActionConfig())
    schema_cancel = cancel_act.get_openai_function()["parameters"]
    assert "user_message" in schema_cancel["properties"]
    assert "user_message" in schema_cancel["required"]


@pytest.mark.asyncio
async def test_resilient_chatgpt_agent_injects_fallback_user_message():
    """Verify ResilientChatGPTAgent automatically injects a persona filler when omitted by LLM."""
    cfg = ChatGPTAgentConfig(
        initial_message=BaseMessage(text="Hello"),
        prompt_preamble="You are receptionist Chloe.",
        openai_api_key="dummy_key",
    )
    fallback = SmartFallbackAgent(persona="receptionist")
    agent = ResilientChatGPTAgent(config=cfg, fallback_agent=fallback)

    fn_call = FunctionCall(
        name="check_availability",
        arguments=json.dumps({"date": "tomorrow"}),
    )

    agent_input = MagicMock()
    agent_input.conversation_id = "test_conv_masking"

    with patch("vocode.streaming.agent.chat_gpt_agent.ChatGPTAgent.call_function", new_callable=AsyncMock) as mock_super:
        await agent.call_function(fn_call, agent_input)

        # Inspect modified arguments
        parsed_args = json.loads(fn_call.arguments)
        assert "user_message" in parsed_args
        assert "Dr. Smith's calendar" in parsed_args["user_message"]
        assert mock_super.called


@pytest.mark.asyncio
async def test_resilient_chatgpt_agent_preserves_custom_user_message():
    """Verify custom user_message generated by LLM is preserved intact."""
    cfg = ChatGPTAgentConfig(
        initial_message=BaseMessage(text="Hello"),
        prompt_preamble="You are Nova.",
        openai_api_key="dummy_key",
    )
    agent = ResilientChatGPTAgent(config=cfg)

    custom_text = "Checking our slots for you right now, hold on a moment!"
    fn_call = FunctionCall(
        name="check_availability",
        arguments=json.dumps({"date": "2026-10-25", "user_message": custom_text}),
    )

    agent_input = MagicMock()
    agent_input.conversation_id = "test_conv_custom"

    with patch("vocode.streaming.agent.chat_gpt_agent.ChatGPTAgent.call_function", new_callable=AsyncMock) as mock_super:
        await agent.call_function(fn_call, agent_input)

        parsed_args = json.loads(fn_call.arguments)
        assert parsed_args["user_message"] == custom_text
        assert mock_super.called


@pytest.mark.asyncio
async def test_persona_specific_fillers_across_actions():
    """Verify concierge, receptionist, and school_receptionist get distinct tailored fillers."""
    personas_and_expected = [
        ("concierge", "calendar availability"),
        ("receptionist", "Dr. Smith's calendar"),
        ("school_receptionist", "school schedule"),
    ]

    for persona, expected_keyword in personas_and_expected:
        cfg = ChatGPTAgentConfig(
            initial_message=BaseMessage(text="Hi"),
            prompt_preamble="Preamble",
            openai_api_key="key",
        )
        agent = ResilientChatGPTAgent(config=cfg, fallback_agent=SmartFallbackAgent(persona=persona))

        fn_call = FunctionCall(
            name="check_availability",
            arguments=json.dumps({"date": "tomorrow"}),
        )
        agent_input = MagicMock()
        agent_input.conversation_id = "test_conv"

        with patch("vocode.streaming.agent.chat_gpt_agent.ChatGPTAgent.call_function", new_callable=AsyncMock):
            await agent.call_function(fn_call, agent_input)
            args = json.loads(fn_call.arguments)
            assert expected_keyword in args["user_message"], f"Failed for persona '{persona}'"
